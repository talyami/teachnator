    const UI_DICTIONARIES = {
      ar: Object.fromEntries(Object.keys(UI_EN).map(key => [key, key])),
      en: UI_EN
    };
    const readUiLanguage = () => {
      try { return localStorage.getItem('fl_ui_language') === 'en' ? 'en' : 'ar'; }
      catch (_) { return 'ar'; }
    };
    let currentUiLanguage = readUiLanguage();
    // Descriptors are stored in UI state so an open toast/report switches immediately too.
    const uiText = (key, values = {}) => ({ uiKey: key, uiValues: values });
    // Explicit UI error values translate at render time; API text stays verbatim.
    const uiErrorText = (message) => ({ uiErrorText: String(message ?? '') });
    const translateUi = (input, values = {}, language = currentUiLanguage) => {
      if (input == null) return '';
      const descriptor = typeof input === 'object' && input.uiKey;
      const key = descriptor ? input.uiKey : String(input);
      const params = descriptor ? input.uiValues : values;
      const dictionary = UI_DICTIONARIES[language] || UI_DICTIONARIES.ar;
      const text = dictionary[key] || key;
      return text.replace(/\{(\w+)\}/g, (match, name) => {
        if (!Object.prototype.hasOwnProperty.call(params, name)) return match;
        const value = params[name];
        // Only explicit nested UI descriptors are translated; user/API values stay verbatim.
        if (value && typeof value === 'object' && 'uiErrorText' in value) {
          return translateUiError(value.uiErrorText, language);
        }
        return value && typeof value === 'object' && value.uiKey
          ? translateUi(value, {}, language) : String(value ?? '');
      });
    };
    // UI-authored errors remain Arabic internally (existing error classification is unchanged).
    // Display only known UI strings; never run this helper over material or API feedback.
    const translateUiError = (input, language = currentUiLanguage) => {
      if (input && typeof input === 'object') return translateUi(input, {}, language);
      const text = String(input ?? '');
      if (UI_EN[text]) return translateUi(text, {}, language);
      const models = text.match(/^خطأ في جلب النماذج: (\d+)$/);
      if (models) return translateUi('خطأ في جلب النماذج: {status}', { status: models[1] }, language);
      const server = text.match(/^خطأ من الخادم \((\d+)\)$/);
      if (server) return translateUi('خطأ من الخادم ({status})', { status: server[1] }, language);
      return text;
    };


